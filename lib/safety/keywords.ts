/**
 * 关键词库 — AIGC 备案 要求.
 *
 * 这不是审查 — 是把"明显需要走人工 / 直接拒绝"的输入 / 输出
 * 在进入 LLM 前后做一道兜底.
 *
 * 三类:
 * 1. CRISIS_KEYWORDS — 生命安全信号 (自伤 / 自杀), 立刻给热线
 * 2. MEDICAL_KEYWORDS — 医疗诊断信号, 必须告知"找医生"
 * 3. LEGAL_KEYWORDS — 法律咨询信号, 必须告知"找律师"
 * 4. FINANCE_KEYWORDS — 具体投资信号, 必须告知"找财务顾问"
 * 5. BLOCKLIST_KEYWORDS — 严格禁止 (政治敏感 / 涉黄涉暴), 直接拒绝
 *
 * BLOCKLIST 走的是"软拒绝" — 我们不存这条内容, 不发给 LLM, 给中性回复.
 * 不试图分析"用户为什么这么说" — 不存档就是最好的保护.
 *
 * 备注: 这个清单跟 AIGC 备案"关键词库附件"对齐, 但只放公开
 * 可整理的部分. 政治敏感词库要从公开资源 (省网信办示范库) 同步,
 * 不在源码里硬编码完整列表.
 */

// ============================================================================
// 1. L3 危机 (生命安全)
// ============================================================================
export const CRISIS_KEYWORDS: ReadonlyArray<string | RegExp> = [
  // 直接自伤 / 自杀
  '自杀',
  '自残',
  '自伤',
  '想死',
  '不想活',
  /想(?:消失|结束|离开这个世界)/,
  /(?:伤害|了结)(?:自己|这条命)/,
  // 强度信号
  /(?:撑不下去|熬不下去|过不下去)了/,
  /(?:没意义|没必要)(?:再|继续)?活/,
  /反正(?:没人需要|没人在乎)/,
  // 方法描述 (任何提到具体方法都是 P0)
  /(?:跳楼|跳河|跳桥|上吊|割腕|吞药|烧炭|安眠药|过量)/,
  // 时间紧迫
  /(?:今晚|明早|马上|今天)(?:就|要)?(?:结束|了断|去做)/,
];

// ============================================================================
// 2. 医疗 — 必须告知"找医生"
// ============================================================================
export const MEDICAL_KEYWORDS: ReadonlyArray<string | RegExp> = [
  /我是不是(?:有|得了|患上)?(?:抑郁|焦虑|双相|躁郁|强迫|PTSD|OCD|ADHD|自闭)/,
  /(?:该|要不要)吃(?:药|抗抑郁|安眠药|镇定剂)/,
  /(?:能不能|可不可以)停药/,
  /(?:癌|肿瘤|心梗|脑梗|糖尿病|高血压).*?(?:严重|怎么办)/,
  /(?:头痛|胸痛|腹痛).*?(?:好几天|一直|越来越)/,
];

// ============================================================================
// 3. 法律 — 必须告知"找律师"
// ============================================================================
export const LEGAL_KEYWORDS: ReadonlyArray<string | RegExp> = [
  /(?:是否|算不算)违法/,
  /(?:能不能|怎么)起诉/,
  /(?:离婚|继承|遗产).*?(?:财产|怎么分|分割)/,
  /(?:工伤|劳动仲裁|赔偿).*?(?:多少|怎么算)/,
  /(?:合同|协议).*?(?:有效|无效|生效)/,
  /(?:维权|举报|报警)/,
];

// ============================================================================
// 4. 具体投资 — 必须告知"找财务顾问"
// ============================================================================
export const FINANCE_KEYWORDS: ReadonlyArray<string | RegExp> = [
  /(?:该|要不要)(?:买|卖|加仓|清仓|抄底).*?(?:股|基金|房|币|黄金|期货)/,
  /(?:推荐|建议).*?(?:股票|基金|理财产品)/,
  /(?:这只|这支|这个)(?:股票|基金).*?(?:值不值|怎么样|能不能买)/,
  /(?:多少钱|几块|几千|几万).*?(?:进|出|买|卖)/,
];

// ============================================================================
// 5. 严格 BLOCKLIST — 直接拒绝, 不进入 LLM
// 不在这里硬编码政治敏感词库 (要从 AIGC 备案省网信办参考库导)
// ============================================================================
export const BLOCKLIST_KEYWORDS: ReadonlyArray<string | RegExp> = [
  // 涉黄
  /色情|淫秽|裸聊|约炮/,
  // 涉暴 / 极端
  /(?:制作|怎么做).*?(?:炸弹|炸药|枪|武器)/,
  /教.*?(?:杀人|伤人|放火)/,
  // 涉毒
  /(?:大麻|海洛因|冰毒|摇头丸).*?(?:哪里|怎么|买)/,
];

// ============================================================================
// 检测助手
// ============================================================================
function hitAny(text: string, patterns: ReadonlyArray<string | RegExp>): boolean {
  return patterns.some((p) => (typeof p === 'string' ? text.includes(p) : p.test(text)));
}

export function hasCrisisSignal(text: string): boolean {
  return hitAny(text, CRISIS_KEYWORDS);
}

export function hasMedicalQuery(text: string): boolean {
  return hitAny(text, MEDICAL_KEYWORDS);
}

export function hasLegalQuery(text: string): boolean {
  return hitAny(text, LEGAL_KEYWORDS);
}

export function hasFinanceQuery(text: string): boolean {
  return hitAny(text, FINANCE_KEYWORDS);
}

export function hasBlocklist(text: string): boolean {
  return hitAny(text, BLOCKLIST_KEYWORDS);
}
