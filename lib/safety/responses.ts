/**
 * 安全响应模板 — 命中红线时, 不走 LLM, 直接给硬编码回应.
 *
 * 设计原则:
 * 1. 危机 — 第一句承认, 立刻给资源, 一个小动作.
 * 2. 医疗 / 法律 / 财务 — 简短承认 + 划清边界 + 转介.
 * 3. Blocklist — 中性拒绝, 不分析, 不教育.
 *
 * 所有响应都不带鸡汤, 不带 emoji, 不超过 150 字.
 */

// ============================================================================
// 1. L3 危机 — 最高优先级
// ============================================================================
export const CRISIS_RESPONSE = `我听见你说的了. 这话我得认真接住.

你现在能拨这个电话: 北京心理危机干预中心 24 小时 010-82951332,
或者全国心理援助热线 400-161-9995.

你身边有没有一个能让你说一句"我不太好"的人? 哪怕只是发条消息说"今晚陪我一下". 你不需要一个人扛.`;

// ============================================================================
// 2. 医疗
// ============================================================================
export const MEDICAL_RESPONSE = `这个判断要见医生 — 我不能也不该替精神科 / 医生做诊断.

你现在描述的状态, 值得让一个真正能开诊断和处方的人看一下. 如果你愿意,
我可以陪你想"怎么挂上号 / 怎么跟家人开这个口" — 但"是不是 X 病"这事我必须让给医生.`;

// ============================================================================
// 3. 法律
// ============================================================================
export const LEGAL_RESPONSE = `这种问题要咨询律师 — 我没办法替你做法律判断.

我可以陪你梳理"你想要什么结果 / 哪些信息要先准备好", 但具体怎么走、能不能赢、
要不要起诉, 都需要见过你材料的律师才能说.`;

// ============================================================================
// 4. 具体投资
// ============================================================================
export const FINANCE_RESPONSE = `具体某只股 / 某套房 / 某个基金值不值得买, 要咨询专业财务顾问.

但我可以陪你想"家庭整体资源配置" — 哪些钱是底, 哪些可以承担风险, 哪些是养老
线动不得. 这个框架我能给, 具体标的不行.`;

// ============================================================================
// 5. Blocklist (涉黄 / 涉暴 / 涉毒 / 极端)
// ============================================================================
export const BLOCKLIST_RESPONSE = `这个话题我不参与. 你可以换一个想聊的事.`;

// ============================================================================
// 联合类型 — 让上层用 switch 处理
// ============================================================================
export type SafetyTrigger = 'crisis' | 'medical' | 'legal' | 'finance' | 'blocklist';

export function getSafetyResponse(trigger: SafetyTrigger): string {
  switch (trigger) {
    case 'crisis': return CRISIS_RESPONSE;
    case 'medical': return MEDICAL_RESPONSE;
    case 'legal': return LEGAL_RESPONSE;
    case 'finance': return FINANCE_RESPONSE;
    case 'blocklist': return BLOCKLIST_RESPONSE;
  }
}
